
-- BAKERY POS SYSTEM
-- POSTGRESQL USER ROLES AND PERMISSIONS

-- 1. CREATE A READ-ONLY ROLE
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'bakery_viewer'
    ) THEN
        CREATE ROLE bakery_viewer NOLOGIN;
    END IF;
END
$$;

-- 2. CREATE A STAFF ROLE
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'bakery_staff'
    ) THEN
        CREATE ROLE bakery_staff NOLOGIN;
    END IF;
END
$$;

-- 3. GIVE VIEWERS READ-ONLY ACCESS
GRANT CONNECT ON DATABASE bakerypos_db TO bakery_viewer;
GRANT USAGE ON SCHEMA public TO bakery_viewer;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO bakery_viewer;

-- 4. GIVE STAFF PERMISSION TO WORK WITH RECORDS
GRANT CONNECT ON DATABASE bakerypos_db TO bakery_staff;
GRANT USAGE ON SCHEMA public TO bakery_staff;
GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA public TO bakery_staff;

GRANT USAGE, SELECT
ON ALL SEQUENCES IN SCHEMA public TO bakery_staff;

-- 5. APPLY PERMISSIONS TO FUTURE TABLES
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT ON TABLES TO bakery_viewer;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO bakery_staff;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT USAGE, SELECT ON SEQUENCES TO bakery_staff;
